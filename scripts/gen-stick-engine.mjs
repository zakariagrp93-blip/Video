// Builds src/shared/stickEngine.generated.ts from vendor/stick-engine (MIT, claude-animation-skills).
// Run: node scripts/gen-stick-engine.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dir = path.join(root, 'vendor/stick-engine');
// Small helpers the example reel defines in its own shot file, offered to every reel.
const APP_HELPERS = `
// ---- app helpers (from the example reel) ----
const C = (base, extra) => Object.assign({}, base, extra);
const walkLegs = (t, sp = 9, amp = .55) => ({ L: [Math.sin(t * sp) * amp + .05, -Math.max(0, Math.sin(t * sp + 1)) * .7], R: [-Math.sin(t * sp) * amp + .05, -Math.max(0, -Math.sin(t * sp + 1)) * .7] });
const walkArms = (t, sp = 9, amp = .6) => ({ L: [.3 - Math.sin(t * sp) * amp, -.3], R: [.3 + Math.sin(t * sp) * amp, -.3] });
const handheld = (t, a = 4) => shake(t * .35, a, 1, 2);
`;
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8');
// Captions are drawn by the app, in its own font: default text font → the bundled Montserrat.
const engine = ['lib.js', 'chars.js', 'env.js'].map((f) => `// ---- ${f} ----\n${read(f)}`).join('\n').replace(/font = 'Poppins'/g, "font = 'FVS Montserrat'") + APP_HELPERS;
const example = read('example-shots.js');

// Top-level names: functions and const declarations (including comma lists like "const W = 1, H = 2").
const names = new Set();
for (const m of engine.matchAll(/^function\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
for (const m of engine.matchAll(/^const\s+(.+?);?\s*$/gm)) {
  let depth = 0, cur = '';
  const parts = [];
  for (const ch of m[1]) {
    if ('([{'.includes(ch)) depth++;
    if (')]}'.includes(ch)) depth--;
    if (ch === ',' && depth === 0) { parts.push(cur); cur = ''; } else cur += ch;
  }
  parts.push(cur);
  for (const p of parts) { const n = /^\s*([A-Za-z_$][\w$]*)\s*=/.exec(p); if (n) names.add(n[1]); }
}
// Verify every name resolves when the engine is evaluated on its own.
const list = [...names].sort();
const probe = new Function(`${engine}\nreturn { ${list.join(', ')} };`)();
const missing = list.filter((n) => probe[n] === undefined);
if (missing.length) throw new Error(`Engine names not defined: ${missing.join(', ')}`);

const out = path.join(root, 'src/shared/stickEngine.generated.ts');
fs.writeFileSync(
  out,
  `// GENERATED by scripts/gen-stick-engine.mjs from vendor/stick-engine — do not edit.\n// Stick-figure canvas engine from claude-animation-skills, MIT License © 2026 Artem Novitckii.\n/* eslint-disable */\nexport const STICK_ENGINE_SOURCE: string = ${JSON.stringify(engine)};\nexport const STICK_ENGINE_NAMES: readonly string[] = ${JSON.stringify(list)};\nexport const STICK_EXAMPLE_SHOTS: string = ${JSON.stringify(example)};\n`,
);
console.log(`Wrote ${list.length} engine names, ${(fs.statSync(out).size / 1024).toFixed(0)} KB → ${path.relative(root, out)}`);
