// Extracts the illustrations used by the vector library from Microsoft Fluent Emoji
// (MIT license, https://github.com/microsoft/fluentui-emoji) via @iconify-json/fluent-emoji
// and writes them to src/remotion/props/fluent.generated.ts. Run: node scripts/gen-fluent-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const set = require('@iconify-json/fluent-emoji/icons.json');
const info = require('@iconify-json/fluent-emoji/info.json');

/** App asset → Fluent Emoji name. Assets not listed keep their hand-drawn version. */
const MAP = {
  banknote: 'euro-banknote',
  bank: 'classical-building',
  house: 'house-with-garden',
  car: 'automobile',
  phone: 'mobile-phone',
  'credit-card': 'credit-card',
  laptop: 'laptop',
  clock: 'alarm-clock',
  building: 'office-building',
  shop: 'convenience-store',
  calendar: 'tear-off-calendar',
  gift: 'wrapped-gift',
  wallet: 'purse',
  briefcase: 'briefcase',
  receipt: 'receipt',
  plane: 'airplane',
  diploma: 'scroll',
  'shopping-bag': 'shopping-bags',
  lock: 'locked',
  hourglass: 'hourglass-not-done',
  coffee: 'hot-beverage',
  yacht: 'motor-boat',
  'question-mark': 'red-question-mark',
  exclamation: 'red-exclamation-mark',
  trophy: 'trophy',
  'graduation-cap': 'graduation-cap',
};

const out = {};
for (const [asset, name] of Object.entries(MAP)) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Fluent Emoji icon not found: ${name}`);
  out[asset] = { name, body: icon.body, width: icon.width ?? set.width ?? 32, height: icon.height ?? set.height ?? 32 };
}
const file = path.join(root, 'src/remotion/props/fluent.generated.ts');
const header = `// GENERATED by scripts/gen-fluent-assets.mjs — do not edit.\n// Illustrations from Microsoft Fluent Emoji (${info.license.title} license, ${info.license.url}).\n// Copyright (c) Microsoft Corporation.\n/* eslint-disable */\n`;
fs.writeFileSync(file, `${header}export const FLUENT: Record<string, { name: string; body: string; width: number; height: number }> = ${JSON.stringify(out)};\n`);
console.log(`Wrote ${Object.keys(out).length} illustrations to ${path.relative(root, file)} (${(fs.statSync(file).size / 1024).toFixed(0)} KB)`);
