// Writes the illustrations chosen in scripts/icon-picks.json (one openly licensed emoji
// set per asset — Fluent Emoji MIT / Noto Emoji Apache-2.0) to
// src/remotion/props/fluent.generated.ts. Assets set to "keep" (or not listed) keep
// their hand-drawn version. Run: node scripts/gen-fluent-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ASSETS, SETS, resolve } from './icon-catalog.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const picks = JSON.parse(fs.readFileSync(path.join(root, 'scripts/icon-picks.json'), 'utf8'));

const out = {};
const used = new Set();
for (const [asset, , emoji] of ASSETS) {
  const key = picks[asset];
  if (!key || key === 'keep') continue;
  const set = SETS.find((s) => s.key === key);
  if (!set) throw new Error(`Unknown pick "${key}" for ${asset}`);
  const r = resolve(set, emoji);
  out[asset] = { name: `${set.pkg}:${r.name}`, body: r.body, width: r.w, height: r.h };
  used.add(set.pkg);
}
const credits = {
  'fluent-emoji': 'Microsoft Fluent Emoji 3D — MIT license, Copyright (c) Microsoft Corporation',
  'fluent-emoji-flat': 'Microsoft Fluent Emoji Flat — MIT license, Copyright (c) Microsoft Corporation',
  'fluent-emoji-high-contrast': 'Microsoft Fluent Emoji High Contrast — MIT license, Copyright (c) Microsoft Corporation',
  noto: 'Google Noto Emoji — Apache License 2.0, Copyright Google Inc.',
};
const file = path.join(root, 'src/remotion/props/fluent.generated.ts');
const header = `// GENERATED by scripts/gen-fluent-assets.mjs from scripts/icon-picks.json — do not edit.\n${[...used].map((u) => `// Illustrations: ${credits[u]}.`).join('\n')}\n/* eslint-disable */\n`;
fs.writeFileSync(file, `${header}export const FLUENT: Record<string, { name: string; body: string; width: number; height: number }> = ${JSON.stringify(out)};\n`);
console.log(`Wrote ${Object.keys(out).length} illustrations (${[...used].join(', ')}) to ${path.relative(root, file)} (${(fs.statSync(file).size / 1024).toFixed(0)} KB)`);
